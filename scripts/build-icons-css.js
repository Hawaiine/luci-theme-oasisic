#!/usr/bin/env node
/**
 * Generate icons.css for Oasisic theme.
 * Intercepts LuCI's built-in /resources/icons/*.svg with CSS content: url().
 * Supports light/dark themes via [data-darkmode] selector.
 * 
 * Usage: node build-icons-css.js > htdocs/luci-static/oasisic/icons.css
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ICONS_ROOT = path.join(__dirname, 'oasisic-icons-batch1');
const THEMES = ['light', 'dark'];
const CATEGORIES = ['network', 'menu'];

function sha256(content) {
	return crypto.createHash('sha256').update(content).digest('hex').slice(0, 8);
}

function scanIcons(category, theme) {
	const dir = path.join(ICONS_ROOT, category, theme);
	if (!fs.existsSync(dir)) return [];
	return fs.readdirSync(dir)
		.filter(f => f.endsWith('.svg'))
		.map(f => {
			const fullPath = path.join(dir, f);
			const content = fs.readFileSync(fullPath, 'utf8');
			const hash = sha256(content);
			const name = f.replace('.svg', '');
			return { name, file: f, hash, category, theme };
		});
}

function buildCSS() {
	const allIcons = [];
	for (const cat of CATEGORIES) {
		for (const theme of THEMES) {
			allIcons.push(...scanIcons(cat, theme));
		}
	}

	const lightIcons = allIcons.filter(i => i.theme === 'light');
	const darkIcons = allIcons.filter(i => i.theme === 'dark');

	let css = `/*\n * Oasisic theme icons - GENERATED by build-icons-css.js\n`;
	css += ` * Intercepts LuCI's /resources/icons/*.svg with content: url().\n`;
	css += ` * Light theme: default; dark theme: [data-darkmode="true"].\n */\n\n`;

	// Light theme (default)
	css += `/* Light theme (default) */\n`;
	for (const icon of lightIcons) {
		const relPath = `icons/${icon.category}/${icon.theme}/${icon.file}`;
		css += `img[src*="/resources/icons/${icon.name}.svg"] { content: url("${relPath}?h=${icon.hash}"); }\n`;
	}

	css += `\n/* Dark theme */\n`;
	css += `[data-darkmode="true"] img[src*="/resources/icons/"] {\n`;
	for (const icon of darkIcons) {
		const relPath = `icons/${icon.category}/${icon.theme}/${icon.file}`;
		css += `  &[src*="${icon.name}.svg"] { content: url("${relPath}?h=${icon.hash}"); }\n`;
	}
	css += `}\n`;

	return css;
}

if (require.main === module) {
	console.log(buildCSS());
}

module.exports = { buildCSS };
